package app.halo.cloud

import java.io.File
import java.util.Base64
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertTrue
import org.junit.Assert.fail
import org.junit.Test

/**
 * The executable half of docs/specs/crypto-parity.md. These vectors are GENERATED BY THE SWIFT
 * IMPLEMENTATION (scripts/gen_crypto_vectors.swift) and the Swift suite re-checks the same file
 * against the real CryptoService, so passing here means Kotlin reproduces what the Mac does —
 * byte-for-byte for the KDF, and by successful decryption for the (randomly-nonced) ciphertexts.
 */
class ParityTest {

    private val vectors: JsonObject = Json.parseToJsonElement(
        File(System.getProperty("halo.vectors") ?: error("halo.vectors not set")).readText()
    ).jsonObject

    private fun JsonObject.str(k: String) = getValue(k).jsonPrimitive.content
    private fun JsonObject.int(k: String) = getValue(k).jsonPrimitive.int
    private fun JsonObject.list(k: String): List<JsonObject> = getValue(k).jsonArray.map { it.jsonObject }
    private fun b64(s: String) = Base64.getDecoder().decode(s)
    private fun hex(b: ByteArray) = Base64.getEncoder().encodeToString(b)

    private fun expectKind(kind: CryptoException.Kind, what: String, block: () -> Unit) {
        try { block(); fail("$what: expected $kind but nothing was thrown") }
        catch (e: CryptoException) { assertEquals(what, kind, e.kind) }
    }

    @Test fun `the file's constants match this implementation`() {
        val a = vectors.getValue("algorithm").jsonObject
        assertEquals(2, vectors.int("version"))
        assertEquals(a.int("defaultIterations"), CryptoService.DEFAULT_ITERATIONS)
        assertEquals(a.int("legacyIterations"), CryptoService.LEGACY_ITERATIONS)
        assertEquals(a.int("minimumIterations"), CryptoService.MINIMUM_ITERATIONS)
        assertEquals(a.int("minimumSaltBytes"), CryptoService.MINIMUM_SALT_BYTES)
        assertEquals(a.str("aad"), String(CryptoService.ENVELOPE_AAD, Charsets.UTF_8))
        assertEquals(a.int("passphraseMinimumLength"), PassphrasePolicy.MINIMUM_LENGTH)
        assertEquals(a.int("passphraseMinimumDistinct"), PassphrasePolicy.MINIMUM_DISTINCT_CHARACTERS)
        assertEquals(32, a.int("keyBytes"))
    }

    @Test fun `KDF vectors reproduce byte for byte`() {
        val list = vectors.list("kdfVectors")
        assertTrue(list.isNotEmpty())
        for (v in list) {
            val key = CryptoService.deriveKey(v.str("passphrase"), b64(v.str("saltB64")), v.int("iterations"))
            assertEquals(v.str("name"), v.str("derivedKeyB64"), hex(key))
        }
    }

    @Test fun `v1 envelopes sealed by Swift decrypt here`() {
        val list = vectors.list("decryptVectors")
        assertTrue(list.isNotEmpty())
        for (v in list) {
            assertTrue(v.str("name"), v.str("ciphertext").startsWith("v1:"))
            val svc = CryptoService.create(v.str("passphrase"), b64(v.str("saltB64")), v.int("iterations"))
            assertEquals(v.str("name"), v.str("plaintext"), svc.decrypt(v.str("ciphertext")))
        }
    }

    @Test fun `legacy v0 boxes still decrypt`() {
        val list = vectors.list("legacyDecryptVectors")
        assertTrue(list.isNotEmpty())
        for (v in list) {
            assertFalse(v.str("name"), v.str("ciphertext").startsWith("v1:"))
            val svc = CryptoService.create(v.str("passphrase"), b64(v.str("saltB64")), v.int("iterations"))
            assertEquals(v.str("name"), v.str("plaintext"), svc.decrypt(v.str("ciphertext")))
        }
    }

    @Test fun `stripped or forged prefixes are rejected`() {
        val list = vectors.list("rejectVectors")
        assertTrue(list.isNotEmpty())
        for (v in list) {
            val svc = CryptoService.create(v.str("passphrase"), b64(v.str("saltB64")), v.int("iterations"))
            assertEquals("decryptionFailed", v.str("expect"))
            expectKind(CryptoException.Kind.DECRYPTION_FAILED, v.str("name")) { svc.decrypt(v.str("ciphertext")) }
        }
    }

    @Test fun `passphrase policy verdicts match including the NFC-before-counting case`() {
        val list = vectors.list("passphraseVectors")
        assertTrue(list.isNotEmpty())
        for (v in list) {
            assertEquals(v.str("passphrase"), v.str("verdict"), PassphrasePolicy.evaluate(v.str("passphrase")).code)
        }
    }

    @Test fun `pairing payloads decode and validate exactly as the contract says`() {
        val list = vectors.list("pairingVectors")
        assertTrue(list.isNotEmpty())
        for (v in list) {
            val p = PairingPayload.decode(v.str("payloadB64"))
            val name = v.str("name")
            assertEquals(name, v.getValue("valid").jsonPrimitive.content.toBoolean(), p.isValid)
            assertEquals(name, v.int("schema"), p.schema)
            assertEquals(name, v.int("iterations"), p.iterations)
            assertEquals(name, v.str("saltB64"), p.saltBase64)
        }
    }

    // ---- behaviours the vectors cannot express (they need randomness or a failing input) ----

    @Test fun `round trip and a fresh nonce every time`() {
        val svc = CryptoService.create("correct horse battery staple", ByteArray(16) { it.toByte() }, CryptoService.MINIMUM_ITERATIONS)
        val a = svc.encrypt("Your OTP is 192699 — ₹12,185.00 日本語 🔐")
        val b = svc.encrypt("Your OTP is 192699 — ₹12,185.00 日本語 🔐")
        assertTrue(a.startsWith("v1:"))
        assertNotEquals(a, b)
        assertEquals("Your OTP is 192699 — ₹12,185.00 日本語 🔐", svc.decrypt(a))
        assertEquals("", svc.decrypt(svc.encrypt("")))
    }

    @Test fun `a wrong passphrase or salt cannot decrypt`() {
        val salt = ByteArray(16) { 7 }
        val good = CryptoService.create("the right passphrase", salt, CryptoService.MINIMUM_ITERATIONS)
        val ct = good.encrypt("secret")
        expectKind(CryptoException.Kind.DECRYPTION_FAILED, "wrong passphrase") {
            CryptoService.create("the wrong passphrase", salt, CryptoService.MINIMUM_ITERATIONS).decrypt(ct)
        }
        expectKind(CryptoException.Kind.DECRYPTION_FAILED, "wrong salt") {
            CryptoService.create("the right passphrase", ByteArray(16) { 8 }, CryptoService.MINIMUM_ITERATIONS).decrypt(ct)
        }
    }

    @Test fun `malformed ciphertext is reported as malformed`() {
        val svc = CryptoService.create("a passphrase", ByteArray(16), CryptoService.MINIMUM_ITERATIONS)
        for (bad in listOf("not base64 @@@", "YWJj", "v1:@@@", "v1:YWJj", "", "v1:")) {
            expectKind(CryptoException.Kind.BAD_CIPHERTEXT, bad) { svc.decrypt(bad) }
        }
    }

    @Test fun `unsafe KDF inputs are refused`() {
        val ok = ByteArray(16) { 1 }
        expectKind(CryptoException.Kind.INVALID_PARAMETERS, "empty passphrase") { CryptoService.deriveKey("", ok, CryptoService.MINIMUM_ITERATIONS) }
        expectKind(CryptoException.Kind.INVALID_PARAMETERS, "short salt") { CryptoService.deriveKey("x", ByteArray(15), CryptoService.MINIMUM_ITERATIONS) }
        expectKind(CryptoException.Kind.INVALID_PARAMETERS, "weak iterations") { CryptoService.deriveKey("x", ok, CryptoService.MINIMUM_ITERATIONS - 1) }
        expectKind(CryptoException.Kind.INVALID_PARAMETERS, "zero iterations") { CryptoService.deriveKey("x", ok, 0) }
    }

    @Test fun `salts are random, correctly sized and never all zero`() {
        repeat(64) { assertTrue(CryptoService.generateSalt().any { it != 0.toByte() }) }
        assertEquals(16, CryptoService.generateSalt().size)
        assertFalse(CryptoService.generateSalt().contentEquals(CryptoService.generateSalt()))
    }

    @Test fun `a new pairing payload is schema 2, valid, and its iteration count cannot be downgraded`() {
        val cfg = FirebaseConfig("k", "p", "a", "s", "https://x.firebaseio.com")
        val p = PairingPayload.create(cfg, CloudAuthCredential("u@halo", "pw"), ByteArray(16) { 3 })
        assertEquals(2, p.schema)
        assertEquals(CryptoService.DEFAULT_ITERATIONS, p.iterations)
        assertTrue(p.isValid)
        assertFalse(p.copy(iterations = CryptoService.MINIMUM_ITERATIONS).isValid)
        assertFalse(p.copy(auth = CloudAuthCredential("u@halo", "attacker")).isValid)
        assertArrayEquals(ByteArray(16) { 3 }, p.salt)
    }

    @Test fun `malformed pairing codes throw rather than produce a payload`() {
        for (bad in listOf("not base64 @@@", Base64.getEncoder().encodeToString("{}".toByteArray()), Base64.getEncoder().encodeToString("nope".toByteArray()))) {
            expectKind(CryptoException.Kind.BAD_CIPHERTEXT, bad) { PairingPayload.decode(bad) }
        }
    }

    // ---- Kotlin -> Swift: opt-in. Writes ciphertext the Swift suite (HALO_KOTLIN_SEALED) must open. ----

    @Test fun `seal vectors for the Swift side to open`() {
        val out = System.getProperty("halo.sealedOut") ?: return        // opt-in; see crypto-parity.md
        val pass = "kotlin sealed this one"
        val salt = ByteArray(16) { (0x30 + it).toByte() }
        val text = "Sealed by Kotlin: A/C *XX3833 debited ₹1,250.00 — 日本語 ☕"
        val svc = CryptoService.create(pass, salt, CryptoService.DEFAULT_ITERATIONS)
        val json = """{"passphrase":"$pass","saltB64":"${Base64.getEncoder().encodeToString(salt)}","iterations":${CryptoService.DEFAULT_ITERATIONS},"plaintext":"$text","ciphertext":"${svc.encrypt(text)}"}"""
        File(out).writeText(json)
    }
}
