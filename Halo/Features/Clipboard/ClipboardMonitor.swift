import Foundation
import AppKit

// MARK: - Clipboard privacy (nspasteboard.org convention)

/// Pasteboard types that mean "do not record this". Password managers, and apps that put one-time
/// data on the pasteboard, mark it so clipboard managers skip it — see http://nspasteboard.org.
/// Honouring the markers is what stops a copied password from landing in history, and — with
/// F-045 enabled — from being encrypted and uploaded to the user's cloud.
///
/// This is about *what Halo records*, independent of the opt-in "don't sync likely secrets" text
/// filter (which guesses from content). A marker is the source app saying so explicitly, so it
/// needs no opt-in and no heuristics.
enum ClipboardPrivacy {
    static let concealed = "org.nspasteboard.ConcealedType"
    static let transient = "org.nspasteboard.TransientType"
    static let autoGenerated = "org.nspasteboard.AutoGeneratedType"

    /// Every marker we honour: the three standard ones plus the older vendor-specific ones that
    /// predate the convention and are still emitted by installed apps.
    static let doNotRecord: Set<String> = [
        concealed, transient, autoGenerated,
        "com.agilebits.onepassword",             // 1Password (legacy)
        "de.petermaurer.TransientPasteboardType", // pre-convention transient marker
        "com.typeit4me.clipping",                // TypeIt4Me expansions
        "Pasteboard generator type"              // Apple's "generated by an app, not the user"
    ]

    static func shouldIgnore(types: [String]) -> Bool {
        types.contains { doNotRecord.contains($0) }
    }

    /// Put a secret on the pasteboard the way a password manager does: readable by whoever the user
    /// pastes into, but marked so Halo's own monitor (and any other clipboard manager that honours the
    /// convention) skips it. Without the marker, a copied credential lands in clipboard history and —
    /// with F-045 on — is encrypted and uploaded to the cloud.
    static func writeConcealed(_ text: String, to pasteboard: NSPasteboard = .general) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        pasteboard.setData(Data(), forType: NSPasteboard.PasteboardType(concealed))
    }
}

// MARK: - Clipboard Monitor
// Polls NSPasteboard every 0.8 seconds for changes.
// In production, wraps detection in a background NSTimer via RunLoop.

@MainActor
final class ClipboardMonitor: ObservableObject {
    @Published var latestItem: ClipboardItem? = nil

    var suppressNext = false
    private var timer: Timer?
    private let pasteboard: NSPasteboard
    private var lastChangeCount: Int
    private let onNewItem: (ClipboardItem) -> Void

    /// `pasteboard` is injectable so tests can drive the real poll path against a private
    /// pasteboard instead of the user's actual clipboard.
    init(pasteboard: NSPasteboard = .general, onNewItem: @escaping (ClipboardItem) -> Void) {
        self.pasteboard = pasteboard
        self.lastChangeCount = pasteboard.changeCount
        self.onNewItem = onNewItem
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.8, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in self?.poll() }
        }
        RunLoop.main.add(timer!, forMode: .common)
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func poll() {
        let pb = pasteboard
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        if suppressNext { suppressNext = false; return }
        // The source app marked this as a secret / one-time value: don't record it at all.
        if ClipboardPrivacy.shouldIgnore(types: (pb.types ?? []).map(\.rawValue)) { return }

        guard let item = extractItem(from: pb) else { return }
        latestItem = item
        onNewItem(item)
    }

    // MARK: - Content Extraction

    private func extractItem(from pb: NSPasteboard) -> ClipboardItem? {
        let sourceApp = NSWorkspace.shared.frontmostApplication?.localizedName

        // Image
        if let data = pb.data(forType: .tiff) ?? pb.data(forType: .png) {
            let meta = imageMetadata(from: data)
            return ClipboardItem(content: .image(data, metadata: meta),
                                 copiedDate: Date(), sourceApp: sourceApp)
        }

        // Color
        if let color = pb.readObjects(forClasses: [NSColor.self], options: nil)?.first as? NSColor {
            let hex = color.hexString ?? "#000000"
            return ClipboardItem(content: .color(hex: hex), copiedDate: Date(), sourceApp: sourceApp)
        }

        // String-based types
        guard let string = pb.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }

        // URL
        if let url = URL(string: string.trimmingCharacters(in: .whitespacesAndNewlines)),
           let scheme = url.scheme, ["http", "https", "ftp", "file"].contains(scheme) {
            return ClipboardItem(content: .url(url), copiedDate: Date(), sourceApp: sourceApp)
        }

        // Code detection
        if looksLikeCode(string) {
            let lang = detectLanguage(string)
            return ClipboardItem(content: .code(string, language: lang),
                                 copiedDate: Date(), sourceApp: sourceApp)
        }

        // Plain text
        return ClipboardItem(content: .text(string), copiedDate: Date(), sourceApp: sourceApp)
    }

    private func looksLikeCode(_ text: String) -> Bool {
        let indicators = ["func ", "class ", "struct ", "let ", "var ", "import ",
                         "def ", "const ", "function ", "return ", "if (", "for (", "=>", "->",
                         "#!/", "#include", "package ", "public class"]
        let matches = indicators.filter { text.contains($0) }.count
        return matches >= 2 && text.contains("\n")
    }

    private func detectLanguage(_ text: String) -> String? {
        if text.contains("func ") && (text.contains("var ") || text.contains("let ")) { return "swift" }
        if text.contains("def ") || text.contains("import os") || text.contains("print(") { return "python" }
        if text.contains("function ") || text.contains("const ") || text.contains("=>") { return "javascript" }
        if text.contains("fun ") && text.contains("val ") { return "kotlin" }
        if text.contains("public class") || text.contains("System.out") { return "java" }
        if text.contains("#include") || text.contains("std::") { return "cpp" }
        return nil
    }

    private func imageMetadata(from data: Data) -> String? {
        guard let image = NSImage(data: data) else { return nil }
        let size = image.size
        let kb = data.count / 1024
        return String(format: "%.0f×%.0f px · %d KB", size.width, size.height, kb)
    }
}

// MARK: - NSColor Hex Extension

private extension NSColor {
    var hexString: String? {
        guard let color = self.usingColorSpace(.sRGB) else { return nil }
        let r = Int(color.redComponent * 255)
        let g = Int(color.greenComponent * 255)
        let b = Int(color.blueComponent * 255)
        return String(format: "#%02X%02X%02X", r, g, b)
    }
}
